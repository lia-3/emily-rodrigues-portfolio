package uva.poo.puerto;

/**
 * Enum que representa el estado de un muelle.
 * Puede estar en uno de los siguientes estados:
 * <ul>
 *   <li><b>OPERATIVO</b>: El muelle está en funcionamiento.</li>
 *   <li><b>FUERA DE SERVICIO</b>: El muelle no está en funcionamiento.</li>
 * </ul>
 * @author Marta Pérez
 * @author Emily Rodrigues
 */

public enum EstadoMuelle {
    OPERATIVO,
    FUERA_DE_SERVICIO
}
